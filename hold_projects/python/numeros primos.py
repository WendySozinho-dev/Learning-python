#detector de numeros primos 
print("digite um numero e a maquina te dira se e primo")
z=int(input("digite  "))
som=0
for a in range(1 ,z+1):
      if z%a==(0):
          som+=1                                     
if som==(2):
        print("e um numero primo")      
else:
      print("nao e um numero primo")
              